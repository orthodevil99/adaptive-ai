import logging

from app.config import Settings
from app.providers.base import TextProvider

logger = logging.getLogger(__name__)


def build_provider(settings: Settings) -> TextProvider | None:
    """Return the configured provider, or None when it cannot be built (analysis still works)."""
    if settings.provider == "mock":
        from app.providers.mock_provider import MockProvider

        logger.warning("Using the MOCK provider: responses are not generated by a real model")
        return MockProvider()
    if not settings.groq_configured:
        return None
    try:
        from app.providers.groq_provider import GroqProvider

        return GroqProvider(
            api_key=settings.groq_api_key.get_secret_value(),
            model=settings.groq_model,
            fallback_model=settings.groq_fallback_model,
            timeout=settings.model_timeout_seconds,
            max_retries=settings.max_retries,
            reasoning=settings.groq_reasoning,
            max_concurrency=settings.max_concurrent_generations,
        )
    except Exception:  # noqa: BLE001
        logger.exception("Could not initialise the Groq provider (is the `groq` package installed?)")
        return None
